if __name__ == "__main__":
    print("Action Potential Curve Fitter — Demo")
    print("=" * 52)

    # Generate data from the original potential() function and add noise.
    # This is representative of fitting to a real AP trace that follows the
    # same ODE model.
    t_demo   = np.linspace(4.90, 25.0, 400)
    y_clean  = np.array([potential(t) for t in t_demo])

    rng      = np.random.default_rng(seed=7)
    sigma    = 0.3                                   # mV noise std dev
    y_noisy  = y_clean + rng.normal(0.0, sigma, size=len(t_demo))

    print(f"\n  Data    : {len(t_demo)} points, "
          f"t ∈ [{t_demo[0]:.2f}, {t_demo[-1]:.2f}] ms")
    print(f"  Noise σ : {sigma} mV")
    print(f"  Noise floor (n·σ²): {len(t_demo) * sigma**2:.2f}\n")

    # Fit — uses INITIAL_PARAMS as x0 (the hardcoded values from potential())
    fitted_params = fit_potential(t_demo, y_noisy)

    # Check how well the fitted model reproduces the noiseless ground truth
    y_fitted     = evaluate(t_demo, fitted_params)
    residuals    = np.abs(y_fitted - y_clean)
    print(f"  Fit quality vs noiseless ground truth:")
    print(f"    Max residual : {residuals.max():.4f} mV")
    print(f"    Mean residual: {residuals.mean():.4f} mV")
    print()
    print(f"  Fitted params array: {fitted_params}")